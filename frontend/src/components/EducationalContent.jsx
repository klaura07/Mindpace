import "./EducationalContent.css";

const HEADINGS = new Map([
  ["EDUCATIONAL NOTES", "Educational notes"],
  ["KEY FACTS", "Key facts"],
  ["IMPORTANT UPDATES", "Important updates"],
]);

export default function EducationalContent({ content, id }) {
  const sources = new Map(content.sources.map(source => [source.id, source]));
  const cite = text => text.split(/(\[\d+\])/g).map((part, index) => {
    const source = /^\[\d+\]$/.test(part) && sources.get(Number(part.slice(1, -1)));
    return source ? <a key={index} href={source.url} target="_blank" rel="noopener noreferrer"
      aria-label={`Source ${source.id}: ${source.title}`}>{part}</a> : part;
  });

  return <article className="educational-content" aria-labelledby={`${id}-title`}>
    <h3 id={`${id}-title`}>{content.title}</h3>
    {content.web_verified === false && <p className="educational-content-meta">These notes are not checked against live web sources and may miss recent developments.</p>}
    <p className="educational-content-meta">Generated by Gemini · {new Date(content.generated_at).toLocaleDateString()}</p>
    <div className="educational-content-body">
      {content.text.split(/\n/).filter(line => line.trim()).map((line, index) => {
        const heading = HEADINGS.get(line.trim().replace(/^#+\s*|\*\*/g, "").replace(/:$/, "").toUpperCase());
        return heading ? <h4 key={index}>{heading}</h4> : <p key={index}>{cite(line)}</p>;
      })}
    </div>
    {content.sources.length > 0 && <><h4>Sources</h4>
    <ul className="educational-content-sources">
      {content.sources.map(source => <li key={source.id}>
        <a href={source.url} target="_blank" rel="noopener noreferrer">[{source.id}] {source.title}</a>
      </li>)}
    </ul></>}
    {content.search_suggestions && <iframe className="educational-content-search" title="Google Search suggestions"
      srcDoc={content.search_suggestions} sandbox="allow-popups allow-popups-to-escape-sandbox" referrerPolicy="no-referrer" />}
  </article>;
}
